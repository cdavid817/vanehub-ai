#!/usr/bin/env node
// Renders the agent capability matrix from its curated source after cross-checking that source
// against the registries in code (see agent-capability-matrix-validate.mjs for what is checked).
//
// README and the guides used to repeat per-agent counts and capabilities by hand; each new agent
// then drifted every page independently. They now reference this file, and `--check` fails CI
// when the committed matrix no longer matches the source or the source no longer matches code.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { validateSource } from "./agent-capability-matrix-validate.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(root, "docs/reference/agents/capability-matrix.source.json");
const TARGET_MD = resolve(root, "docs/reference/agents/capability-matrix.md");
const TARGET_JSON = resolve(root, "docs/reference/agents/capability-matrix.json");

const STATUS_LEGEND = {
  stable: "in the current stable download",
  main: "implemented on `main`, not yet in a stable release",
  legacy: "detect-only terminal entry, no managed conversation",
};
const TRANSPORT_LABEL = {
  "native-api": "native API",
  headless: "terminal PTY + headless",
  "acp-stdio": "terminal PTY + ACP stdio",
  "terminal-only": "terminal PTY only",
};
const PROJECTION_LABEL = {
  "catalog-policy-governed": "catalog policy-governed parameters",
  "runtime-flags-pty-only-under-acp": "runtime flags on PTY; read-only flag only under ACP, host answers per call",
  "runtime-flags-terminal-only": "runtime flags on the PTY (`--plan|--default|--autoEdit|--yolo`); no managed conversation",
  "hook-plus-permission-mode": "`--permission-mode` + PreToolUse hook",
  "host-policy-native": "host policy directly",
};
const RELAY_LABEL = {
  relayed: "managed relay",
  "own-config": "CLI's own configuration",
  "acp-own-config": "CLI's own configuration (`mcpServers: []` on the ACP handshake)",
  none: "none",
  "native-tools": "native tool catalog",
};
const USAGE_LABEL = {
  "headless-and-terminal": "terminal collector + headless reported",
  "headless-reported": "headless reported only",
  unavailable: "unavailable (never shown as zero)",
  "native-accounting": "native model-invocation accounting",
};

function escape(text) {
  return String(text).replaceAll("|", "\\|");
}

function installSummary(agent) {
  return agent.installSources
    .map((source) => {
      if (source.kind === "npm") return `npm \`${source.package}\``;
      if (source.kind === "winget") return `WinGet \`${source.id}\``;
      if (source.kind === "vendor") return `vendor installer (${source.platforms.join(", ")})`;
      if (source.kind === "detect-only") return "detect-only";
      return source.kind;
    })
    .join("; ");
}

function liveSummary(agent) {
  const { platforms } = agent.liveQualification;
  return platforms.length === 0 ? "fixture-qualified" : `live-qualified: ${platforms.join(", ")}`;
}

export function buildSnapshot(source, audit) {
  return {
    stableRelease: source.stableRelease,
    upstreamReviewedAt: audit.reviewedAt,
    upstreamExpandedReviewedAt: audit.expandedReviewedAt,
    agents: source.agents.map((agent) => ({
      ...agent,
      liveQualification: {
        ...agent.liveQualification,
        upstreamVersion: audit.binaries[agent.id] ?? null,
        upstreamSource: audit.sources[agent.id] ?? null,
        verifiedOn: audit.sources[agent.id]
          ? agent.releaseStatus === "stable" ? audit.reviewedAt : audit.expandedReviewedAt
          : null,
      },
    })),
  };
}

export function render(snapshot) {
  const lines = [
    "# Agent capability matrix",
    "",
    "<!-- Generated by scripts/generate-agent-capability-matrix.mjs from",
    "     docs/reference/agents/capability-matrix.source.json, cross-checked against the code",
    "     registries. Do not edit by hand; run `npm run docs:agents:generate`. -->",
    "",
    `Current stable release: **${snapshot.stableRelease}**. Status vocabulary is defined in [terminology](../terminology.md):`,
    "",
    ...Object.entries(STATUS_LEGEND).map(([key, text]) => `- \`${key}\` — ${text};`),
    "- `fixture-qualified` — automated fixture suites pass; no recorded real-CLI run on any platform;",
    "- `live-qualified: <os>` — a real-CLI run is recorded for the listed operating systems only.",
    "",
    "Three verbs are kept apart throughout: **upstream supports** (the CLI itself can do it), **VaneHub manages** (VaneHub writes or drives it), **VaneHub verifies** (a recorded test proves it). \"VaneHub does not manage X\" never means \"upstream does not support X\".",
    "",
    "## Matrix",
    "",
    "| Agent | Status | Transport | Managed chat | Install source | Auth probe | Provider config | Permission projection | MCP | In execution trace | Evaluation | Usage reporting | Qualification |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const agent of snapshot.agents) {
    lines.push(
      [
        "",
        `${agent.displayName} (\`${agent.id}\`)`,
        agent.stableSince ? `${agent.releaseStatus} (${agent.stableSince})` : agent.releaseStatus,
        TRANSPORT_LABEL[agent.transport],
        agent.managedChat ? "yes" : "no",
        escape(installSummary(agent)),
        agent.authProbe,
        agent.providerConfig,
        escape(PROJECTION_LABEL[agent.permissionProjection]),
        escape(RELAY_LABEL[agent.mcpRelay]),
        agent.executionTrace ? "yes" : "no",
        agent.evaluationCandidate ? "candidate" : "excluded",
        escape(USAGE_LABEL[agent.usageReporting]),
        liveSummary(agent),
        "",
      ].join(" | ").trim(),
    );
  }
  lines.push(
    "",
    "## Permission projection notes",
    "",
    "A policy template (`readonly`, `standard`, `trusted`, `yolo`) is enforced at the host decision point for every agent. What the CLI process is launched with is a separate projection and differs by transport; `trusted` and `yolo` project identically except on Qwen Code, Kimi Code CLI, and iFlow CLI terminals. Per-template flags are tabulated in the developer guide's [permission model](../../developer-guide/src/permission-model.md).",
    "",
    "| Agent | Enforceability |",
    "| --- | --- |",
    ...snapshot.agents.map((agent) => `| ${agent.displayName} | ${escape(agent.enforceabilityNotes)} |`),
    "",
    "## Provider configuration notes",
    "",
    "`exclusive` — VaneHub writes one active profile into the CLI's own configuration file and restores the previous values on switch; `additive` — VaneHub adds its entry beside existing ones (OpenCode); `apply-only` — VaneHub applies model/approval fields but manages no endpoint or credential field; `not-applicable` — the CLI exposes no third-party endpoint VaneHub could manage; `native-catalog` — OnePiece's own provider catalog.",
    "",
    "| Agent | Managed file | Note |",
    "| --- | --- | --- |",
    ...snapshot.agents.map(
      (agent) => `| ${agent.displayName} | ${agent.providerConfigFile ? `\`${agent.providerConfigFile}\`` : "—"} | ${escape(agent.providerConfigNotes ?? "—")} |`,
    ),
    "",
    "## Auth probe notes",
    "",
    "`signed-in` means VaneHub can read the CLI's own login status; `unknown` means only the version is probed and the settings page never starts a login. Vendor subscription login always happens in your terminal.",
    "",
    ...snapshot.agents
      .filter((agent) => agent.authProbeNotes)
      .map((agent) => `- **${agent.displayName}** — ${agent.authProbeNotes}`),
    "",
    "## Evaluation notes",
    "",
    "Candidates are every registered agent whose capability tags do not include `legacy`; available agents are preselected, at most eight per arena.",
    "",
    ...snapshot.agents
      .filter((agent) => !agent.evaluationCandidate)
      .map((agent) => `- **${agent.displayName}** — excluded: ${agent.evaluationReason}`),
    "",
    "## Upstream sources and freshness",
    "",
    `Official source URLs and the binary versions the parameter catalog was audited against come from \`src/contracts/fixtures/cli-parameter-source-audit.json\` (original five reviewed ${snapshot.upstreamReviewedAt}; expanded providers reviewed ${snapshot.upstreamExpandedReviewedAt}). Installation scripts, login flows, and quotas change upstream; confirm any \`curl | sh\` installer against the official source before running it.`,
    "",
    "| Agent | Official source | Audited version | Reviewed | Qualification evidence |",
    "| --- | --- | --- | --- | --- |",
    ...snapshot.agents
      .filter((agent) => agent.liveQualification.upstreamSource)
      .map(
        (agent) =>
          `| ${agent.displayName} | <${agent.liveQualification.upstreamSource}> | ${agent.liveQualification.upstreamVersion} | ${agent.liveQualification.verifiedOn} | ${escape(agent.liveQualification.source)} |`,
      ),
  );
  return `${lines.join("\n").replace(/\s+$/, "")}\n`;
}

function stale(path, output) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : "";
  return current !== output ? relative(root, path).split(sep).join("/") : null;
}

function main() {
  const check = process.argv.includes("--check");
  const source = JSON.parse(readFileSync(SOURCE, "utf8"));
  const { problems, audit } = validateSource(source, root);
  if (problems.length > 0) {
    console.error("capability-matrix.source.json disagrees with the code:\n- " + problems.join("\n- "));
    process.exit(1);
  }
  const snapshot = buildSnapshot(source, audit);
  const markdown = render(snapshot);
  const json = `${JSON.stringify(snapshot, null, 2)}\n`;
  if (check) {
    const staleFiles = [stale(TARGET_MD, markdown), stale(TARGET_JSON, json)].filter(Boolean);
    if (staleFiles.length > 0) {
      console.error(
        `${staleFiles.join(", ")} stale.\nRun \`npm run docs:agents:generate\` and commit the result. Never hand-edit it.`,
      );
      process.exit(1);
    }
    console.log("agent capability matrix is up to date");
    return;
  }
  mkdirSync(dirname(TARGET_MD), { recursive: true });
  writeFileSync(TARGET_MD, markdown, "utf8");
  writeFileSync(TARGET_JSON, json, "utf8");
  console.log(`wrote ${TARGET_MD} and ${TARGET_JSON}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
