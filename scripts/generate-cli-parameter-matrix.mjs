#!/usr/bin/env node
// Renders the documented provider parameter matrix from the canonical registry.
//
// The matrix is generated rather than written because a hand-maintained table drifts silently: it
// looks authoritative long after a flag has been renamed. `--check` fails the build when the
// committed file no longer matches the registry.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(
  root,
  "src-tauri/src/contexts/tooling/cli_parameters/catalog/catalog.v2.json",
);
const TARGET = resolve(root, "docs/agent-infrastructure/cli-parameter-matrix.md");

const AGENT_NAMES = {
  "claude-code": "Claude Code",
  "codex-cli": "Codex CLI",
  "gemini-cli": "Gemini CLI",
  opencode: "OpenCode",
  "antigravity-cli": "Antigravity CLI",
};

function flagOf(renderer) {
  if (renderer.kind === "positive-negative-flag") {
    return `${renderer.positiveFlag} / ${renderer.negativeFlag}`;
  }
  if (renderer.kind === "config-key-value") {
    return `${renderer.flag} ${renderer.key}=…`;
  }
  return renderer.flag;
}

function escape(text) {
  return text.replaceAll("|", "\\|");
}

function render(catalog) {
  const lines = [
    "# CLI parameter matrix",
    "",
    "<!-- Generated by scripts/generate-cli-parameter-matrix.mjs from",
    "     src-tauri/src/contexts/tooling/cli_parameters/catalog/catalog.v2.json.",
    "     Do not edit by hand; run `npm run docs:matrix:generate`. -->",
    "",
    `Catalog version \`${catalog.catalogVersion}\`, selection schema \`${catalog.selectionSchemaVersion}\`.`,
    "",
    "`Ownership` decides where a parameter is edited. Only `user-editable` entries appear on",
    "Settings → CLI Parameters; `policy-governed` entries belong to Agent Permission Policies and",
    "`runtime-reserved` entries belong to the launch itself.",
    "",
  ];

  for (const agent of catalog.agents) {
    const name = AGENT_NAMES[agent.agentId] ?? agent.agentId;
    lines.push(`## ${name}`, "");
    lines.push(
      "| Parameter | Flag | Slot | Scope | Control | Ownership | Min version | Verification |",
      "| --- | --- | --- | --- | --- | --- | --- | --- |",
    );
    for (const parameter of agent.parameters) {
      const audit = parameter.audit ?? {};
      lines.push(
        [
          "",
          `\`${parameter.id}\``,
          `\`${escape(flagOf(parameter.renderer))}\``,
          parameter.renderer.slot,
          parameter.launchScopes.join(", "),
          parameter.control,
          parameter.ownership ?? "user-editable",
          parameter.compatibility?.minVersion ?? "—",
          audit.verification ?? "—",
          "",
        ].join(" | ").trim(),
      );
    }
    lines.push("");
    const sources = [
      ...new Set(agent.parameters.map((parameter) => parameter.audit?.sourceUrl).filter(Boolean)),
    ];
    if (sources.length > 0) {
      lines.push(`Source: ${sources.map((url) => `<${url}>`).join(", ")}`, "");
    }
  }

  // Each section ends with a blank separator; the last one would otherwise leave a blank line
  // at end of file, which `git diff --check` reports.
  return `${lines.join("\n").replace(/\s+$/, "")}\n`;
}

function main() {
  const check = process.argv.includes("--check");
  const output = render(JSON.parse(readFileSync(SOURCE, "utf8")));
  if (check) {
    const current = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";
    if (current !== output) {
      console.error(
        "docs/reference/cli-parameter-matrix.md is stale.\n" +
          "Run `npm run docs:matrix:generate` and commit the result. Never hand-edit it.",
      );
      process.exit(1);
    }
    console.log("cli-parameter matrix is up to date");
    return;
  }
  mkdirSync(dirname(TARGET), { recursive: true });
  writeFileSync(TARGET, output, "utf8");
  console.log(`wrote ${TARGET}`);
}

main();
